#!/usr/bin/env node
/**
 * Generates framework wrappers from @elo-ui/components' Custom Elements Manifest.
 *
 * Usage (from a wrapper package directory): elo-wrapper-gen <react|vue|angular>
 * Writes to ./src/generated/. Output is not committed; it's regenerated on build.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { readElements } from './manifest.js';
import { generateReact } from './targets/react.js';
import { generateVue } from './targets/vue.js';
import { generateAngular } from './targets/angular.js';

const targets = { react: generateReact, vue: generateVue, angular: generateAngular };

const target = process.argv[2];
if (!(target in targets)) {
  console.error(`Usage: elo-wrapper-gen <${Object.keys(targets).join('|')}>`);
  process.exit(1);
}

const require = createRequire(join(process.cwd(), 'package.json'));
const manifestPath = require.resolve('@elo-ui/components/custom-elements.json');
const elements = readElements(JSON.parse(readFileSync(manifestPath, 'utf8')));

const outDir = join(process.cwd(), 'src', 'generated');
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const header = '// Generated by @elo-ui/wrapper-gen from custom-elements.json. Do not edit.\n';
const files = targets[target](elements);
for (const [name, contents] of Object.entries(files)) {
  writeFileSync(join(outDir, name), header + contents);
}

console.log(`[wrapper-gen] ${target}: ${elements.length} element(s) → src/generated/`);
